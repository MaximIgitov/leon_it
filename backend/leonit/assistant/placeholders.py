"""Подсказки-сценарии для пустого чата.

У каждой роли свой набор: рекрутеру — про вакансии и вопросы, владельцу —
плюс команда и настройки, нанимающему менеджеру — только про кандидатов, к
которым он допущен. Клик по подсказке отправляет её текст как сообщение,
поэтому формулировки — законченные просьбы, а не заголовки.
"""

from __future__ import annotations

_RECRUITER: tuple[str, ...] = (
    "Создай вакансию Python-разработчика по описанию: бэкенд на FastAPI, PostgreSQL, "
    "уровень middle, опыт от 3 лет",
    "Сгенерируй 6 вопросов по рубрике для открытой вакансии",
    "Вычитай вопросы вакансии и предложи, что улучшить",
    "Срез по вакансии: воронка по статусам и топ кандидатов",
    "Кого из кандидатов стоит пригласить повторно",
    "Какие этапы найма в нашей компании и какой у нас стек",
)

_OWNER: tuple[str, ...] = (
    *_RECRUITER,
    "Кто из участников давно не заходил",
    "Срез по всем вакансиям за неделю",
    "Проверь настройки моделей",
)

_HIRING_MANAGER: tuple[str, ...] = (
    "Сравни трёх лучших кандидатов по вакансии",
    "Что проверить на созвоне с кандидатом, чей отчёт открыт",
    "Объясни заключение по кандидату простыми словами",
)

PLACEHOLDERS: dict[str, tuple[str, ...]] = {
    "recruiter": _RECRUITER,
    "owner": _OWNER,
    "hiring_manager": _HIRING_MANAGER,
}


def placeholders_for(role: str) -> list[str]:
    return list(PLACEHOLDERS.get(role, _HIRING_MANAGER))
